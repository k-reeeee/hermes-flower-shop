#!/usr/bin/env node
// Bundle desktop/src/**/*.js into the single ESM file the Hermes desktop loader reads:
// desktop/plugin.js. Only @hermes/plugin-sdk, react and react/jsx-runtime stay as
// imports (the loader resolves nothing else). Output is unminified + ASCII-only so a
// catalog reviewer can read it and Windows codepages cannot mangle it.
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, statSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))

function findEsbuild() {
  const candidates = [
    process.env.ESBUILD_BIN,
    path.join(root, 'node_modules', '.bin', 'esbuild'),
    path.join(os.homedir(), '.hermes', 'hermes-agent', 'node_modules', '.bin', 'esbuild')
  ].filter(Boolean)
  for (const c of candidates) if (existsSync(c)) return c
  return 'esbuild' // PATH
}

const esbuild = findEsbuild()
const out = path.join(root, 'desktop', 'plugin.js')
const args = [
  path.join(root, 'desktop', 'src', 'index.js'),
  '--bundle',
  '--format=esm',
  '--platform=browser',
  '--target=es2022',
  '--charset=ascii',
  '--legal-comments=inline',
  '--external:@hermes/plugin-sdk',
  '--external:react',
  '--external:react/jsx-runtime',
  `--define:__FLOWERSHOP_VERSION__=${JSON.stringify(pkg.version)}`,
  `--banner:js=// Flower Shop desktop half v${pkg.version} - GENERATED by scripts/build-desktop.mjs from desktop/src. Do not edit by hand.`,
  `--outfile=${out}`,
  '--log-level=warning'
]
const r = spawnSync(esbuild, args, { stdio: 'inherit' })
if (r.status !== 0) process.exit(r.status ?? 1)

// Post-build guards (same rules `hermes plugins validate` + the desktop loader enforce).
const code = readFileSync(out, 'utf8')
const bad = []
if (/[^\x00-\x7f]/.test(code)) bad.push('non-ASCII byte in output')
const imports = [...code.matchAll(/^import\s.*?from\s+["']([^"']+)["']/gm)].map(m => m[1])
for (const s of imports) if (!['@hermes/plugin-sdk', 'react', 'react/jsx-runtime'].includes(s)) bad.push(`forbidden import ${s}`)
if (/\beval\s*\(|new Function\s*\(/.test(code)) bad.push('eval/new Function present')
if (/\bimport\s*\(/.test(code)) bad.push('dynamic import() present')
if (bad.length) { console.error('build guard FAILED:\n - ' + bad.join('\n - ')); process.exit(2) }
console.log(`built ${path.relative(root, out)} (${statSync(out).size} bytes, v${pkg.version})`)
